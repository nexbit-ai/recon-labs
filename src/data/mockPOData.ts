  apptDate: string;
  dispatchedDate: string;
  expiryDate: string;
  skusCount: number;
  ordQty: number;
  recQty: number;
  shortQty: number;
  acceptedQty: number;
  rejectedQty: number;
  poAmount: number;
  invoicedAmount: number;
  invoiceNumber: string;
  invoiceDate: string;
  grnNumber: string;
  grnDate: string;
  paymentStatus: 'Paid' | 'Partial' | 'Pending' | 'Overdue';
  settledAmount: number;
  discrepancyAmount: number;
  discrepancyReason: string;
  leadTimeDays: number;
  fillRatePercent: number;
  ewayBill: string;
  facilityCode: string;
